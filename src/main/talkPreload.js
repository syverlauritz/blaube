const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('blaubeTalk', {
  onState: (cb) => ipcRenderer.on('talk-state', (_e, s) => cb(s)),
  onRefused: (cb) => ipcRenderer.on('talk-refused', (_e, key) => cb(key)),
  onTail: (cb) => ipcRenderer.on('talk-tail', (_e, t) => cb(t)),
  setHeight: (id, h) => ipcRenderer.send('talk-height', id, h),
  send: (id, text) => ipcRenderer.send('talk-send', id, text),
  paste: (id, bytes, type) => ipcRenderer.invoke('talk-paste', id, bytes, type),
  pathOf: (file) => { try { return webUtils.getPathForFile(file); } catch { return ''; } },
  hub: () => ipcRenderer.invoke('talk-hub'),
  searchAll: (q) => ipcRenderer.invoke('talk-search', q),
  searchPast: (q) => ipcRenderer.invoke('talk-search-past', q),
  complete: (id, kind, q) => ipcRenderer.invoke('talk-complete', id, kind, q),
  mode: (id, mode) => ipcRenderer.send('talk-mode', id, mode),
  filesExist: (id, paths) => ipcRenderer.invoke('talk-files-exist', id, paths),
  peekFile: (id, rel) => ipcRenderer.invoke('talk-peek', id, rel),
  bringHere: (id) => ipcRenderer.send('talk-bring', id),
  image: (id, file) => ipcRenderer.invoke('talk-image', id, file),
  attach: (id) => ipcRenderer.invoke('talk-attach', id),
  answer: (id, key, choice) => ipcRenderer.send('talk-answer', id, key, choice),
  later: (id, at) => ipcRenderer.send('talk-later', id, at),
  gitRun: (id, run) => ipcRenderer.send('talk-git-run', id, run),
  install: (id) => ipcRenderer.send('talk-install', id),
  makeEnv: (id) => ipcRenderer.send('talk-make-env', id),
  settle: (id, file, side) => ipcRenderer.invoke('talk-settle', id, file, side),
  merged: (id) => ipcRenderer.invoke('talk-merged', id),
  web: (id) => ipcRenderer.invoke('talk-web', id),
  revert: (id, hash) => ipcRenderer.invoke('talk-revert', id, hash),
  deleteMerged: (id, names) => ipcRenderer.invoke('talk-delete-merged', id, names),
  signIn: (id) => ipcRenderer.send('talk-sign-in', id),
  taskOutput: (id, taskId) => ipcRenderer.invoke('talk-task-output', id, taskId),
  stopTask: (id, taskId) => ipcRenderer.invoke('talk-stop-task', id, taskId),
  mcpReconnect: (id, name) => ipcRenderer.invoke('talk-mcp-reconnect', id, name),
  mcpSignIn: (id, name) => ipcRenderer.invoke('talk-mcp-sign-in', id, name),
  clone: (text, opts) => ipcRenderer.invoke('talk-clone', text, opts),
  newProject: (name, opts) => ipcRenderer.invoke('talk-new-project', name, opts),
  issue: (text, opts) => ipcRenderer.invoke('talk-issue', text, opts),
  githubTodo: () => ipcRenderer.invoke('talk-github-todo'),
  rewind: (id, uuid) => ipcRenderer.invoke('talk-rewind', id, uuid),
  editFrom: (id, uuid, text) => ipcRenderer.invoke('talk-edit', id, uuid, text),
  background: (id) => ipcRenderer.send('talk-background', id),
  forward: (from, to, text) => ipcRenderer.send('talk-forward', from, to, text),
  diff: (id, file) => ipcRenderer.invoke('talk-diff', id, file),
  undoCommit: (id, hash) => ipcRenderer.invoke('talk-undo-commit', id, hash),
  discard: (id, file) => ipcRenderer.invoke('talk-discard', id, file),
  putBack: (id) => ipcRenderer.invoke('talk-put-back', id),
  branches: (id) => ipcRenderer.invoke('talk-branches', id),
  commits: (id) => ipcRenderer.invoke('talk-commits', id),
  branchChanges: (id) => ipcRenderer.invoke('talk-branch-changes', id),
  branchDiff: (id, rel) => ipcRenderer.invoke('talk-branch-diff', id, rel),
  commit: (id, hash) => ipcRenderer.invoke('talk-commit', id, hash),
  parked: (id) => ipcRenderer.invoke('talk-parked', id),
  switchBranch: (id, name, create) => ipcRenderer.invoke('talk-switch-branch', id, name, create),
  earlier: (id) => ipcRenderer.invoke('talk-earlier', id),
  newIn: (folder, opts) => ipcRenderer.send('talk-new', folder, opts),
  pickUp: (id) => ipcRenderer.send('talk-pickup', id),
  continueHere: (id) => ipcRenderer.send('talk-continue', id),
  switchTo: (id) => ipcRenderer.send('talk-switch', id),
  copy: (text) => ipcRenderer.send('talk-copy', text),
  openLink: (url) => ipcRenderer.send('talk-link', url),
  reveal: (id, file) => ipcRenderer.send('talk-reveal', id, file),
  openInEditor: (id, rel, line) => ipcRenderer.send('talk-open-editor', id, rel, line || 0),
  save: (id) => ipcRenderer.invoke('talk-save', id),
  copyAll: (id) => ipcRenderer.send('talk-copy-all', id),
  showFile: (file) => ipcRenderer.send('talk-show-file', file),
  dragOut: (id, file) => ipcRenderer.send('talk-drag', id, file),
  stop: (id) => ipcRenderer.send('talk-stop', id),
  unsend: (id, n) => ipcRenderer.send('talk-unsend', id, n),
  decide: (id, key, choice, answers) => ipcRenderer.send('talk-permission', id, key, choice, answers),
  close: () => ipcRenderer.send('talk-close'),
  closing: () => ipcRenderer.send('talk-closing'),
  terminal: () => ipcRenderer.send('talk-terminal'),
});
